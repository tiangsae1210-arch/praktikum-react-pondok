CREATE TABLE IF NOT EXISTS admins (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  username VARCHAR(60) NOT NULL UNIQUE,
  email VARCHAR(190) NOT NULL UNIQUE,
  password VARCHAR(255) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS santri (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nis VARCHAR(40) NOT NULL UNIQUE,
  nama VARCHAR(150) NOT NULL,
  jenis_kelamin VARCHAR(20) NOT NULL CHECK (jenis_kelamin IN ('Laki-laki','Perempuan')),
  kelas VARCHAR(80) NOT NULL,
  asrama VARCHAR(100) NOT NULL DEFAULT '',
  no_hp_wali VARCHAR(30) NOT NULL,
  alamat TEXT NOT NULL,
  tanggal_masuk DATE NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'Aktif' CHECK (status IN ('Aktif','Tidak Aktif')),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_santri_nama ON santri (nama);
CREATE INDEX IF NOT EXISTS idx_santri_status ON santri (status);

CREATE TABLE IF NOT EXISTS tagihan (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  santri_id INTEGER NOT NULL,
  periode CHAR(7) NOT NULL,
  nominal NUMERIC(12,2) NOT NULL CHECK (nominal >= 0),
  syahriah NUMERIC(12,2) DEFAULT NULL,
  diniyah NUMERIC(12,2) DEFAULT NULL,
  listrik_air_bersih NUMERIC(12,2) DEFAULT NULL,
  kebersihan_perlengkapan NUMERIC(12,2) DEFAULT NULL,
  haflah_syahriah NUMERIC(12,2) DEFAULT NULL,
  maklumat NUMERIC(12,2) DEFAULT NULL,
  modul_lks NUMERIC(12,2) DEFAULT NULL,
  kegiatan_kesiswaan NUMERIC(12,2) DEFAULT NULL,
  haflah_madrasah NUMERIC(12,2) DEFAULT NULL,
  total_dibayar NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (total_dibayar >= 0),
  status VARCHAR(20) NOT NULL DEFAULT 'Belum Dibayar' CHECK (status IN ('Belum Dibayar','Belum Lunas','Lunas')),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uniq_santri_periode UNIQUE (santri_id, periode),
  CONSTRAINT fk_tagihan_santri FOREIGN KEY (santri_id) REFERENCES santri(id) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS idx_tagihan_periode ON tagihan (periode);

CREATE TABLE IF NOT EXISTS pembayaran (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kode_transaksi VARCHAR(40) NOT NULL UNIQUE,
  tagihan_id INTEGER NOT NULL,
  tanggal_pembayaran DATE NOT NULL,
  jumlah_bayar NUMERIC(12,2) NOT NULL CHECK (jumlah_bayar >= 0),
  metode_pembayaran VARCHAR(20) NOT NULL CHECK (metode_pembayaran IN ('Tunai','Transfer')),
  keterangan VARCHAR(500) NOT NULL DEFAULT '',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_pembayaran_tagihan FOREIGN KEY (tagihan_id) REFERENCES tagihan(id) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS idx_pembayaran_tanggal ON pembayaran (tanggal_pembayaran);
